 function translateAttrs(el){
  for(const attr of ['placeholder','title','aria-label']){
   const current=el.getAttribute(attr);
   if(current==null)continue;
   let rec=attrOriginals.get(el);
   if(!rec){rec={};attrOriginals.set(el,rec);}
   const old=rec[attr],source=old&&current===old.last?old.source:current;
   const value=source.trim();
   if(!value)continue;
   const translated=language==='zh'?chinese(value):value;
   const next=source.replace(value,translated);
   rec[attr]={source,last:next};
   if(current!==next)el.setAttribute(attr,next);
  }
 }
