-- SCHEMA ONLY — no data rows, no auth users, no storage files are copied.
-- No RLS policies are created here (see 03_rls_enable.sql); policy
--   definitions were NOT recorded in the live check (only counts per
--   table), so they must not be invented.
-- Method: CREATE TABLEs first (no FK clauses inline), then ADD all FK
--   constraints at the end, so table order does not depend on FK order.
--   FKs to auth.users are kept — auth.users already exists in a new
--   Supabase project.
-- Notes / uncertainties (also listed in README.md):
--   * learning_attempt_reviews.id is bigint PK; no default / identity
--     was recorded — do not assume GENERATED BY DEFAULT AS IDENTITY.
--   * session_id in hsk3_attempt_reviews / hsk4_attempt_reviews /
--     learning_attempt_reviews has no FK recorded — none is added.
--   * approved_by in profiles, created_by in homework_windows have no
--     FK recorded — none is added.
--   * user_id in ntc_game_recipients has no FK recorded — none is added.
--   * Where an FK's ON DELETE action was not given in the report, the
--     constraint is created without an ON DELETE clause (Postgres
--     default NO ACTION). See the FK section below for which ones.
--   * gen_random_uuid() is built-in on Postgres 17 (live is 17.6.1).
